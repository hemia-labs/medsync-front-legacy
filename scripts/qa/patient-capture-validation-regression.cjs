const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const root = path.resolve(__dirname, '../..');
const read = file => fs.readFileSync(path.join(root, file), 'utf8');
const context = { component: null, VuexMixin: {}, moduleTypes: {}, fnTypes: {} };
for(const file of ['src/domain/patient/administrative.validation.js', 'src/domain/clinical-history/vitalSigns.validation.js']) vm.runInNewContext(read(file).replace(/export const /g, 'var '), context);
const today = new Date(2026, 9, 16, 12);
const valid = { name: 'Paciente ficticio', firstSurname: 'QA', birthDate: '2000-10-17', mobilePhone: '(55) 1234-5678', localPhone: '', postalCode: '01234' };
assert.equal(Object.keys(context.patientAdministrativeErrors(valid, today)).length, 0);
assert.equal(context.patientAge(valid.birthDate, today), 25);
assert.equal(context.patientAge('2000-10-16', today), 26);
assert.equal(context.patientAge('2026-10-16', today), 0);
for(const birthDate of ['2030-01-01', '2026-02-31', 'not-a-date']) assert.ok(context.patientAdministrativeErrors({ ...valid, birthDate }, today).birthDate);
for(const [field, value] of [['mobilePhone', 'abc123'], ['mobilePhone', '123'], ['localPhone', '123456789A'], ['postalCode', 'ABCDE'], ['postalCode', '1234']]) assert.ok(context.patientAdministrativeErrors({ ...valid, [field]: value }, today)[field]);
assert.equal(context.normalizePatientPhone('(55) 1234-5678'), '5512345678');
for(const [key, value] of [['weight', '-5'], ['oxygen_saturation', '150'], ['heart_rate', 'abc'], ['respiratory_rate', 'NaN'], ['temperature', '1e3'], ['blood_pressure', '120mmHg']]) assert.ok(context.vitalSignError(key, value));
for(const [key, value] of [['weight', '0.7'], ['temperature', '45'], ['heart_rate', '350'], ['blood_pressure', '300/180'], ['oxygen_saturation', '0'], ['oxygen_saturation', '100'], ['height', '168'], ['height', '1.68']]) assert.equal(context.vitalSignError(key, value), '', 'No arbitrary physiological ceiling');
vm.runInNewContext(read('src/views/Patient/PatientCreate.vue').split('<script>')[1].split('</script>')[0].replace(/^import[\s\S]*?;\r?\n/gm, '').replace('export default', 'component ='), context);
const options = context.component;
const state = { ...options.data(), $nextTick: callback => callback(), $refs: {} };
for(const [key, method] of Object.entries(options.methods)) state[key] = method.bind(state);
for(const [key, getter] of Object.entries(options.computed)) Object.defineProperty(state, key, { get: getter.bind(state) });
let focused = '', writes = 0;
state.focusField = field => { focused = field; };
state.ActionWrapp = async () => { writes++; };
(async () => {
  await state.createPatient();
  assert.equal(focused, 'name', 'Submission returns the mobile user to the first actionable error');
  assert.equal(writes, 0);
  assert.ok(state.fieldError('name').length);
  console.log('PASS patient capture: valid/invalid calendar dates, age boundary, phone normalization, postal code, immediate vital validation, extreme valid values, invalid mobile submission focus. No network or database writes.');
})().catch(error => { console.error(error); process.exitCode = 1; });
