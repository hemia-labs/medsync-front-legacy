const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const root = path.resolve(__dirname, '../..');
const load = (file, context) => {
  const source = fs.readFileSync(path.join(root, file), 'utf8');
  vm.runInNewContext(source.split('<script>')[1].split('</script>')[0].replace(/^import[\s\S]*?;\r?\n/gm, '').replace('export default', 'component ='), context);
  return context.component;
};
const context = { component: null, mapGetters: () => ({}), mapActions: () => ({}), VuexMixin: {}, moduleTypes: {}, fnTypes: {}, DAHistoryHeader: {}, DAAlergyAlert: {}, AllergyEditor: {}, PatientAdministrativeForm: {}, DASweetConfirm: {}, DocumentsAndSignatures: {}, DELETE: {}, DAPxService: {} };
const parent = load('src/views/Patient/PatientShow.vue', context);
const editor = load('src/views/Patient/components/PatientAdministrativeForm.vue', context);
let permissions = ['px.all', 'px.new', 'px.tab.history', 'documents.view'];
const scope = { hasPermission: key => permissions.includes(key), px: { access: { clinical: false }, person: { active: 1 } } };
for (const [key, getter] of Object.entries(parent.computed)) Object.defineProperty(scope, key, { get: () => getter.call(scope), configurable: true });
Object.assign(scope, parent.data());
assert.equal(scope.canManagePatient, true);
assert.equal(scope.canViewClinical, false);
assert.equal(scope.canEditClinical, false);
assert.equal(scope.canEditAllergies, false);
assert.equal(scope.allowedTabs.some(tab => tab.component === 'da-medical-history'), false);
assert.equal(scope.allowedTabs.some(tab => tab.component === 'da-patient-documents'), true);
permissions = ['px.all', 'px.new', 'clinical_history.view', 'clinical_history.edit_draft', 'px.tab.history'];
assert.equal(scope.canViewClinical, false, 'UI cannot turn redacted administrative response into clinical data');
scope.px.access.clinical = true;
assert.equal(scope.canViewClinical, true);
assert.equal(scope.canEditAllergies, true);
assert.equal(scope.allowedTabs.some(tab => tab.component === 'da-medical-history'), true);
scope.px.person.active = 0; assert.equal(scope.isArchived, true);
permissions = ['px.all']; assert.equal(scope.canManagePatient, false);
const notices = [];
const patient = { person: { id_person: 'qa', name: 'QA', surname: 'Paciente', birthday: '01-02-2000', age: 26, telephone: '1234567890' }, address: { direction: 'Calle QA' } };
const view = { patient, $refs: { form: { validate: () => true } }, $emit: (...event) => notices.push(event) };
Object.assign(view, editor.data.call(view));
for (const [key, method] of Object.entries(editor.methods)) view[key] = method.bind(view);
assert.equal(view.form.person.birthday, '2000-02-01');
assert.equal(patient.person.birthday, '01-02-2000', 'Opening administrative editor does not mutate shared patient');
view.form.person.name = 'Captura pendiente';
(async () => {
  context.DAPxService.updateAdministrative = async () => ({ success: false, message: 'Fallo de conexión' });
  await view.save();
  assert.equal(view.error, 'Fallo de conexión'); assert.equal(view.form.person.name, 'Captura pendiente'); assert.equal(view.saving, false); assert.equal(notices.length, 0);
  context.DAPxService.updateAdministrative = async () => ({ success: true });
  await view.save(); assert.equal(notices[0][0], 'saved'); assert.equal(view.saving, false);
  const header = fs.readFileSync(path.join(root, 'src/views/Patient/components/DAHistoryHeader.vue'), 'utf8');
  assert.match(header, /v-if="showClinical">Afecciones/);
  assert.match(header, /v-if="showClinical" class="patient-badge"/);
  const show = fs.readFileSync(path.join(root, 'src/views/Patient/PatientShow.vue'), 'utf8');
  assert.match(show, /Archivar paciente/); assert.doesNotMatch(show, /Eliminar Paciente/);
  console.log('PASS S16 frontend: administrative-only access, clinical permission plus server projection, archive wording, editor date mapping and retry retains capture.');
})().catch(error => { console.error(error); process.exitCode = 1; });
