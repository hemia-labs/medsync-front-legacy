const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const root=path.join(__dirname,'../..');
const read=file=>fs.readFileSync(path.join(root,file),'utf8');
function domain(file,names,bindings={}) {
  const source=read(file).replace(/^import[^\n]+\n/gm,'').replace(/export (const|function)/g,'$1');
  return new Function(...Object.keys(bindings),source+'\nreturn {'+names.join(',')+'};')(...Object.values(bindings));
}
const agenda=domain('src/domain/onboarding/agendaGuide.js',['stepsFor','agendaPresentation']);
const preparation=domain('src/domain/onboarding/preparationGuide.js',['preparationDefinition','branchRecord']);
const {resumableGuides}=domain('src/domain/onboarding/resumeGuides.js',['resumableGuides'],{...agenda,...preparation});
const values=new Map();
const storage={get length(){return values.size;},key:index=>[...values.keys()][index],getItem:key=>values.get(key)};
