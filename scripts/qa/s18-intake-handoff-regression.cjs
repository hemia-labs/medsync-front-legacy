const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const compiler = require('vue-template-compiler');
const file = path.join(__dirname, '../../src/views/Patient/Sections/ClinicalIntake.vue');
const source = fs.readFileSync(file, 'utf8');
assert.deepEqual(compiler.compile(source.split('<template>')[1].split('</template>')[0]).errors, []);
const context = { component: null, HistoryService: {} };
vm.runInNewContext(source.split('<script>')[1].split('</script>')[0].replace(/^import[^\n]*\r?\n/gm, '').replace('export default', 'component ='), context);
const c = context.component, state = { ...c.data(), px: { person: { id_person: 'qa', fullname: 'QA Patient' } } };
for(const [key, method] of Object.entries(c.methods)) state[key] = method.bind(state);
for(const [key, getter] of Object.entries(c.computed)) Object.defineProperty(state, key, { get: () => getter.call(state) });
const a = { id_doctor_professional_profile: 'a', professional_name: 'Doctora A' }, b = { id_doctor_professional_profile: 'b', professional_name: 'Doctor B' };
const clinic = { editable: true, history: null, consultation: {}, doctors: [a, b], suggested_doctor_profile_id: null, doctor_assignment_locked: false, assigned_doctor_available: true };
let writes = [];
(async () => {
  state.apply(clinic); assert.equal(state.doctorProfileId, null); assert.equal(state.dirty, false);
  state.form.reason = 'Paciente refiere molestia';
  context.HistoryService.saveIntake = async (id, body) => { writes.push(body); return { success: false, message: 'No connection' }; };
  assert.equal(await state.save(), false); assert.equal(writes.length, 0); assert.match(state.doctorError, /Selecciona/);
  state.doctorProfileId = 'b';
  assert.equal(await state.save(), false); assert.equal(writes[0].doctor_responsible_profile_id, 'b');
  assert.equal(writes[0].doctor_responsible_user_id, undefined); assert.equal(state.doctorProfileId, 'b'); assert.equal(state.form.reason, 'Paciente refiere molestia');
  const saved = { ...clinic, history: { id_clinical_history: 'h', revision: 0 }, consultation: { reason: state.form.reason }, responsible_doctor: b, doctor_assignment_locked: true };
  context.HistoryService.saveIntake = async () => ({ success: true, data: saved });
  assert.equal(await state.save(), true); assert.equal(state.doctorAssignmentLocked, true); assert.equal(state.dirty, false);
  assert.match(state.feedback, /Doctor B/);
  state.apply({ ...saved, assigned_doctor_available: false }); state.form.reason = 'More capture';
  assert.equal(await state.save(), false, 'Inactive recipient must be changed by authorized clinical editor');
  state.apply({ ...clinic, doctors: [a], suggested_doctor_profile_id: 'a' });
  assert.equal(state.doctorProfileId, 'a'); assert.equal(state.dirty, false, 'Suggestion alone does not warn on leaving empty new intake');
  state.apply({ ...clinic, history: { id_clinical_history: 'orphan', revision: 8 }, consultation: { reason: 'Existing orphan intake' }, doctors: [a], suggested_doctor_profile_id: 'a' });
  assert.equal(state.dirty, true, 'Suggested doctor can be saved for an existing orphan without altering narrative');
  state.apply(clinic); state.doctorProfileId = 'b';
  const leave = state.confirmLeave(); await state.resolveLeave('discard');
  assert.equal(await leave, true); assert.equal(state.doctorProfileId, null); assert.equal(state.dirty, false);
  console.log('PASS S18 intake UI: compiled template, explicit clinic recipient, profile-only payload, error retains choice/text, assigned doctor readonly, pro suggestion, orphan assignment and dirty/discard handling.');
})().catch(error => { console.error(error); process.exitCode = 1; });
